package io.github.sakurajay.lyra.data.provider.builtin

import io.github.sakurajay.lyra.domain.model.Song
import java.io.IOException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.OkHttpClient
import okhttp3.Request
import org.json.JSONObject

/**
 * 歌单摘要。[listId] 形如 `digest-8__2736267853`：数字前段是酷我内部的 digest 类型，
 * 后段才是该类型下的 id。类型决定详情走哪个端点，所以 id 必须原样带着类型走。
 */
data class PlaylistSummary(
    val listId: String,
    val name: String,
    val author: String,
    val coverUrl: String,
    val songCount: Int,
    val playCountLabel: String,
    val description: String,
)

data class PlaylistDetail(val info: PlaylistSummary, val songs: List<Song>)

class PlaylistException(message: String) : Exception(message)

/**
 * 内置酷我歌单（推荐歌单 + 歌单详情）。
 *
 * 端点、digest 分派与字段映射取自 lx-music-mobile 的 `musicSdk/kw/songList.js`（2026-10 读取）。
 * 榜单接口（pl.svc 之外的 bang_info）与这里的推荐列表是两套东西，不要混用。
 *
 * digest 分派照抄它的规则：8 直接查 pl.svc；13 其实是专辑；5 和其他要先经 q.k 换 sourceid。
 * 专辑那一支复用 [KuwoAlbumProvider]，同一个专辑不允许有第二条取数路径。
 */
class KuwoPlaylistProvider(
    private val client: OkHttpClient = defaultClient(),
    private val albumProvider: KuwoAlbumProvider = KuwoAlbumProvider(client),
) {

    /** 推荐歌单的排序。写在类体里而不是 companion 里：外面要写 `KuwoPlaylistProvider.Order` */
    enum class Order(val id: String, val label: String) { HOT("hot", "最热"), NEW("new", "最新") }

    suspend fun recommended(order: Order = Order.HOT, page: Int = 1, limit: Int = 20): List<PlaylistSummary> =
        withContext(Dispatchers.IO) {
            val url = "$RCM_URL?loginUid=0&loginSid=0&appUid=$APP_UID&pn=$page&rn=$limit&order=${order.id}"
            val body = fetch(url) { "歌单列表 HTTP ${it.code}" }
            val root = runCatching { JSONObject(body) }.getOrElse { throw PlaylistException("歌单列表不是合法 JSON") }
            if (root.optInt("code") != 200) throw PlaylistException("歌单列表 code=${root.optInt("code")}")
            val list = root.optJSONObject("data")?.optJSONArray("data")
                ?: throw PlaylistException("歌单列表没有 data.data：${body.take(120)}")
            List(list.length()) { index -> list.optJSONObject(index)?.let(::toSummary) }.filterNotNull()
        }

    suspend fun detail(listId: String, page: Int = 1): PlaylistDetail = withContext(Dispatchers.IO) {
        val (digest, id) = parseListId(listId)
        when (digest) {
            DIGEST_ALBUM -> {
                val album = albumProvider.detail(id)
                PlaylistDetail(
                    PlaylistSummary(listId, album.info.name, album.info.artist, album.info.artworkUrl, album.info.songCount, "", album.info.description),
                    album.songs,
                )
            }

            DIGEST_LIST -> {
                val sourceId = fetch("$QK_URL?op=query&cont=ninfo&node=$id&pn=0&rn=1&fmt=json&src=mbox&level=2") {
                    "歌单节点 HTTP ${it.code}"
                }.let { JSONObject(it).optJSONArray("child")?.optJSONObject(0)?.optString("sourceid") }
                    .orEmpty()
                if (sourceId.isBlank()) throw PlaylistException("歌单 $id 换不到 sourceid")
                listDetail(sourceId, page)
            }

            else -> listDetail(id, page)
        }
    }

    private fun listDetail(pid: String, page: Int): PlaylistDetail {
        val url = "$PL_URL?op=getlistinfo&pid=$pid&pn=${page - 1}&rn=$LIMIT_SONG&encode=utf8" +
            "&keyset=pl2012&identity=kuwo&pcmp4=1&vipver=MUSIC_9.0.5.0_W1&newver=1"
        val body = fetch(url) { "歌单详情 HTTP ${it.code}" }
        val root = runCatching { JSONObject(body) }.getOrElse { throw PlaylistException("歌单详情不是合法 JSON") }
        if (root.optString("result") != "ok") {
            throw PlaylistException("歌单详情 result=${root.optString("result")}：${body.take(120)}")
        }
        val list = root.optJSONArray("musiclist")
        val songs = List(list?.length() ?: 0) { index -> list?.optJSONObject(index)?.let(::toSong) }.filterNotNull()
        val info = PlaylistSummary(
            listId = "${DIGEST_SONG_LIST}__$pid",
            name = KuwoSearchProvider.decodeName(root.optString("title")),
            author = root.optString("uname").takeUnless { it.isAutoGeneratedName() }.orEmpty(),
            coverUrl = KuwoSearchProvider.firstHttpUrl(root.optString("pic")),
            songCount = root.optString("total").toIntOrNull() ?: songs.size,
            playCountLabel = formatPlayCount(root.optString("playnum")),
            description = KuwoSearchProvider.decodeName(root.optString("info")),
        )
        return PlaylistDetail(info, songs)
    }

    private fun fetch(url: String, failure: (okhttp3.Response) -> String): String =
        try {
            client.newCall(Request.Builder().url(url).header("User-Agent", BuiltinHttp.USER_AGENT).build())
                .execute().use { response ->
                    if (!response.isSuccessful) throw PlaylistException(failure(response))
                    response.body?.string() ?: throw PlaylistException("响应体为空")
                }
        } catch (e: IOException) {
            throw PlaylistException("网络不可达：${e.message}")
        }

    companion object {
        private const val APP_UID = "76039576"
        private const val RCM_URL = "https://wapi.kuwo.cn/api/pc/classify/playlist/getRcmPlayList"
        private const val PL_URL = "https://nplserver.kuwo.cn/pl.svc"
        private const val QK_URL = "https://qukudata.kuwo.cn/q.k"
        private const val LIMIT_SONG = 200
        private const val DIGEST_SONG_LIST = "digest-8"
        private const val DIGEST_LIST = "digest-5"
        private const val DIGEST_ALBUM = "digest-13"

        private fun defaultClient(): OkHttpClient = BuiltinHttp.client(15, 20)

        /**
         * 酷我歌单的作者名经常是 `kw` + 一串数字的机器账号——展示出来没有任何信息量。
         * 认出来就留空，让页面只显示"共 N 首 · X播放"那一行。
         */
        internal fun String.isAutoGeneratedName(): Boolean =
            length > 4 && startsWith("kw", ignoreCase = true) && drop(2).all { it.isDigit() }

        /** 推荐列表与详情返回的歌曲字段不同名，这里只认详情那一份 */
        internal fun parseListId(listId: String): Pair<String, String> {
            val parts = listId.split("__")
            return if (parts.size == 2) parts[0] to parts[1] else DIGEST_SONG_LIST to listId
        }

        internal fun formatPlayCount(raw: String?): String {
            val num = raw?.toLongOrNull() ?: return raw.orEmpty()
            return when {
                num > 100_000_000 -> "%.1f亿".format(num / 1e8)
                num > 10_000 -> "%.1f万".format(num / 1e4)
                else -> num.toString()
            }
        }

        private fun toSummary(item: JSONObject): PlaylistSummary? {
            val name = KuwoSearchProvider.decodeName(item.optString("name"))
            if (name.isBlank()) return null
            return PlaylistSummary(
                listId = "digest-${item.optString("digest")}__${item.optString("id")}",
                name = name,
                author = item.optString("uname"),
                coverUrl = KuwoSearchProvider.firstHttpUrl(item.optString("img")),
                songCount = item.optString("total").toIntOrNull() ?: 0,
                playCountLabel = formatPlayCount(item.optString("listencnt")),
                description = KuwoSearchProvider.decodeName(item.optString("desc")),
            )
        }

        private fun toSong(item: JSONObject): Song? {
            val id = item.optString("id")
            val name = KuwoSearchProvider.decodeName(item.optString("name"))
            if (id.isBlank() || name.isBlank()) return null
            return Song(
                id = id,
                source = "kw",
                name = name,
                artists = KuwoSearchProvider.splitArtists(item.optString("artist")),
                albumName = KuwoSearchProvider.decodeName(item.optString("album")),
                albumId = item.optString("albumid"),
                durationSec = item.optString("duration").toIntOrNull() ?: 0,
                qualities = KuwoSearchProvider.parseQualities(item.optString("N_MINFO")),
                artworkUrl = KuwoSearchProvider.firstHttpUrl(item.optString("pic")),
            )
        }
    }
}
