package io.github.sakurajay.lyra.data.provider.builtin

import io.github.sakurajay.lyra.data.provider.builtin.KuwoPlaylistProvider.Companion.isAutoGeneratedName
import io.github.sakurajay.lyra.data.provider.builtin.KuwoPlaylistProvider.Companion.parseListId
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * 歌单 id 的形态决定详情走哪个端点，播放量与作者名的处理决定页面上会不会出现一串乱码，
 * 这三件事都是纯字符串逻辑，不需要网络就能钉住。
 */
class KuwoPlaylistIdTest {

    @Test
    fun splitsDigestFromIdAndDefaultsToSongList() {
        assertEquals("digest-8" to "3677150229", parseListId("digest-8__3677150229"))
        assertEquals("digest-13" to "123", parseListId("digest-13__123"))
        assertEquals("digest-8" to "2144087549", parseListId("2144087549"))
    }

    @Test
    fun formatsPlayCountInChineseUnits() {
        assertEquals("101.2万", KuwoPlaylistProvider.formatPlayCount("1012458"))
        assertEquals("1.2亿", KuwoPlaylistProvider.formatPlayCount("123456789"))
        assertEquals("861", KuwoPlaylistProvider.formatPlayCount("861"))
        assertEquals("", KuwoPlaylistProvider.formatPlayCount(""))
    }

    @Test
    fun recognizesMachineGeneratedAuthorNames() {
        assertTrue("kw2144087549".isAutoGeneratedName())
        assertFalse("带我走".isAutoGeneratedName())
        assertFalse("kw".isAutoGeneratedName())
        assertFalse("kwab12".isAutoGeneratedName())
    }
}
